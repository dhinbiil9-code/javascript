let today = "monday";

switch (today) {
    case "saturday":
        console.log("go to the coding school");
        break;
    case "sunday":
        console.log("go to the market");
        break;
    case "monday":
        console.log("go to the work");
        break;
    case "tuesday":
        console.log("go to the playing football");
        break;
    case "wednesday":
        console.log("go to the shopping");
        break;
    case "thursday":
        console.log("go to the visit relative");
        break;
    case "friday":
        console.log("go to the mosque");
        break;
    default:
        console.log("no days in here");
}